import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const projectRoot = fileURLToPath(new URL("../", import.meta.url));
const fontDirectory = path.join(projectRoot, "public", "fonts");
const target = path.join(projectRoot, "src", "app", "brand-fonts.css");
const styles = [
  ["Hairline", 250],
  ["Thin", 275],
  ["ExtraLight", 300],
  ["Light", 350],
  ["Regular", 400],
  ["Book", 450],
  ["Medium", 500],
  ["Bold", 700],
  ["Heavy", 800],
  ["Black", 900],
];
const formats = [
  ["woff2", "woff2"],
  ["woff", "woff"],
  ["ttf", "truetype"],
  ["otf", "opentype"],
];
const faces = styles.flatMap(([name, weight]) =>
  ["normal", "italic"].flatMap((style) => {
    const names = [`MarkPro-${name}${style === "italic" ? "Italic" : ""}`];
    if (name === "Regular") names.push(style === "italic" ? "MarkPro-Italic" : "MarkPro");
    const font = formats
      .flatMap(([extension, type]) => names.map((base) => ({ file: `${base}.${extension}`, type })))
      .find(({ file }) => existsSync(path.join(fontDirectory, file)));
    if (!font) return [];
    return [
      {
        weight,
        style,
        css: `@font-face {\n  font-family: "Mark Pro";\n  src: url("/fonts/${font.file}") format("${font.type}");\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n}`,
      },
    ];
  }),
);
const ready = faces.some((face) => face.weight === 400 && face.style === "normal");
const css = ready
  ? `/* Generated by scripts/prepare-fonts.mjs from supplied Mark Pro assets. */\n${faces.map((face) => face.css).join("\n\n")}\n`
  : "/* Generated by scripts/prepare-fonts.mjs. Mark Pro assets are not supplied yet. */\n";
if (!existsSync(target) || readFileSync(target, "utf8") !== css) writeFileSync(target, css);
console.log(
  ready
    ? `Mark Pro: ${faces.length} font face(s) prepared.`
    : "Mark Pro files not supplied; using the Manrope fallback. See public/fonts/README.md.",
);
